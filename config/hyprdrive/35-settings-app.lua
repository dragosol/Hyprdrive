-- hyprdrive fragment 35-settings-app -- the window rules the settings app needs
-- in order to obey the motion law it edits.
--
-- MACHINE-OWNED above the raw-snippet marker; USER-OWNED below it. Everything
-- above BEGIN is rewritten wholesale when this fragment is regenerated;
-- everything between BEGIN and END is carried across verbatim.
--
-- 35, so it lands after the binds in 30 and before 40-45. Those later numbers
-- are written BY the settings app, one per pane; this one is written FOR it and
-- the app never touches it.
--
-- ONE ANIMATION OWNS THE ENTRANCE.
--
-- The app fades its own surface in over Motion.enterMs on an OutCubic and out
-- over Motion.exitMs on an InCubic -- the constants x64 grades it against.
-- Hyprland was ALSO animating the same window: windowsIn is a 260ms popin and
-- fadeIn a 200ms ramp, both perfectly good curves on their own, but they are
-- keyed to the surface mapping rather than to the app starting to draw, and the
-- sum of the two read on film as one linear-ish entrance -- x64 measured
-- half-work at 0.46 against a 0.45 threshold. Two decelerating curves out of
-- phase do not add up to a decelerating curve.
--
-- So the compositor stands down for this one window and the QML curve is the
-- whole motion. The trade is cheap in the direction it costs: what is given up
-- is Hyprland's move/resize animation on one floating settings window, and what
-- is bought is that the motion the user sees is the motion the app declares and
-- the gate reads out of Motion.qml.
--
-- MATCHED BY TITLE, NOT CLASS, and that is not a shortcut. The window's class is
-- org.quickshell -- the same class as illogical-impulse's bar, its own settings
-- window and every other surface in the shell, because Qt takes the Wayland
-- app_id from QGuiApplication::desktopFileName() and quickshell sets that once
-- per process. Quickshell 0.3.0 exposes Quickshell.appId read-only and qs has no
-- flag for it, so there is no distinct class to match on, and a class rule here
-- would silence the animations of the whole shell. The title is set before the
-- first commit -- initialTitle reads "Hyprdrive Settings" on the guest -- so the
-- rule lands at map time, which is when a no_anim rule has to land.
hl.window_rule({ match = { title = "^(Hyprdrive Settings)$" }, no_anim = true })
